import assert from 'node:assert/strict'
import { _electron as electron } from 'playwright'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve, join } from 'node:path'

const option = name => process.argv.find(a => a.startsWith(`--${name}=`))?.slice(name.length + 3)
const exe = option('executable'), output = resolve(option('output') || 'test-results/desktop-panel-design')
mkdirSync(output, { recursive: true })
const env = { ...process.env, WORKBENCH_DATA_DIR: join(output, `profile-${Date.now()}`), WORKBENCH_DISABLE_GPU_AUTO: '1', WORKBENCH_DISABLE_LEGACY_TRANSLATION_ENGINE: '1', WORKBENCH_DISABLE_ARXIV_AUTO: '1', WORKBENCH_DISABLE_METADATA_AUTO: '1', WORKBENCH_DISABLE_ENCOURAGEMENT_AUTO: '1', WORKBENCH_DISABLE_NOTIFICATIONS: '1' }
delete env.ELECTRON_RUN_AS_NODE
const errors = [], checks = []
const app = await electron.launch({ executablePath: resolve(exe || 'node_modules/electron/dist/electron.exe'), args: exe ? [] : ['.'], env })
app.context().setDefaultTimeout(15000)
app.on('window', page => page.on('pageerror', e => errors.push(e.message)))
const unwrap = r => { assert.equal(r.ok, true, JSON.stringify(r)); return r.data }
const pageWith = async needle => { for (let i = 0; i < 100; i++) { const page = app.windows().find(p => p.url().includes(needle)); if (page) return page; await new Promise(r => setTimeout(r, 100)) } throw Error('Missing page ' + needle) }
const pass = text => { checks.push(text); console.log('PASS', text) }
try {
  const rail = await pageWith('rail.html')
  await rail.getByRole('button', { name: 'GPU 监控', exact: true }).click()
  const panel = await pageWith('widget.html')
  await panel.getByRole('switch', { name: 'GPU 空闲提醒' }).uncheck()
  assert.equal(unwrap(await panel.evaluate(() => window.workbench.gpuMonitor())).alerts.enabled, false)
  await panel.getByRole('switch', { name: 'GPU 空闲提醒' }).check()
  assert.equal(unwrap(await panel.evaluate(() => window.workbench.gpuMonitor())).alerts.enabled, true)
  pass('GPU reminder switch saves through the real desktop API')
  await rail.getByRole('button', { name: '打开 PhD 工作台', exact: true }).click()
  const main = await pageWith('index.html')
  await main.getByRole('heading', { name: '今日计划', exact: true }).waitFor()
  const parent = unwrap(await main.evaluate(() => window.workbench.createFolder({ name: '视觉研究', parentId: null })))
  const child = unwrap(await main.evaluate(parentId => window.workbench.createFolder({ name: '在读文献', parentId }), parent.id))
  unwrap(await main.evaluate(() => window.workbench.createFolder({ name: '已读归档', parentId: null })))
  unwrap(await main.evaluate(({ path, id }) => window.workbench.importPapers([path], id, false), { path: resolve('tests/fixtures/translation-check.pdf'), id: child.id }))
  const first = unwrap(await main.evaluate(() => window.workbench.librarySnapshot())).papers[0]
  unwrap(await main.evaluate(id => window.workbench.updatePaper(id, { title: '跨域表面缺陷识别的多模态表示学习' }), first.id))
  const due = new Date(); due.setDate(due.getDate() + 10)
  const upcoming = unwrap(await main.evaluate(revisionDueDate => window.workbench.createSubmission({ title: '面向复杂工业场景的多模态表面缺陷识别', journal: 'IEEE Transactions on Industrial Informatics', manuscriptId: 'TII-2026-1042', stages: [{ name: '已投稿', occurredOn: '2026-10-01' }, { name: '外审中', occurredOn: '2026-10-12' }, { name: '大修', occurredOn: '2026-11-01' }], revisionDueDate, reminderEnabled: false, reminderDays: 3, notes: '补充跨域实验，整理审稿意见对应的修改。' }), due.toLocaleDateString('en-CA')))
  unwrap(await main.evaluate(() => window.workbench.createSubmission({ title: 'Robust Multimodal Perception under Distribution Shift', journal: 'Pattern Recognition', manuscriptId: 'PR-2026-2031', stages: [{ name: '已投稿', occurredOn: '2026-10-20' }, { name: '编辑处理中', occurredOn: '2026-10-28' }], revisionDueDate: null, reminderEnabled: false, reminderDays: 3, notes: '' })))
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('index.html')).minimize())
  await rail.getByRole('button', { name: '论文阅读', exact: true }).click()
  await panel.getByRole('button', { name: '展开目录', exact: true }).click()
  await panel.getByRole('button', { name: '折叠 视觉研究', exact: true }).click()
  assert.equal(await panel.getByRole('button', { name: '在读文献', exact: true }).count(), 0)
  await panel.getByRole('button', { name: '展开 视觉研究', exact: true }).click()
  await panel.getByRole('button', { name: '在读文献', exact: true }).click()
  await panel.getByRole('button', { name: '跨域表面缺陷识别的多模态表示学习', exact: true }).waitFor()
  const second = join(output, 'directory-import.pdf')
  writeFileSync(second, Buffer.concat([readFileSync('tests/fixtures/translation-check.pdf'), Buffer.from('\n% second directory fixture\n')]))
  const box = await panel.locator('.reading-list-heading').boundingBox(), cdp = await app.context().newCDPSession(panel)
  for (const type of ['dragEnter', 'dragOver', 'drop']) await cdp.send('Input.dispatchDragEvent', { type, x: box.x + box.width / 2, y: box.y + box.height / 2, data: { items: [], files: [second], dragOperationsMask: 1 } })
  await panel.getByRole('button', { name: 'directory-import', exact: true }).waitFor()
  const library = unwrap(await panel.evaluate(() => window.workbench.desktopLibrary()))
  assert.ok(library.papers.every(p => p.folderId === child.id))
  const layout = await panel.evaluate(() => { const directory = document.querySelector('.reading-directory').getBoundingClientRect(), papers = document.querySelector('.reading-papers').getBoundingClientRect(); return { directory: directory.toJSON(), papers: papers.toJSON(), width: innerWidth } })
  assert.ok(layout.papers.y >= layout.directory.bottom)
  assert.ok(layout.papers.width > layout.width * .8)
  await panel.waitForTimeout(400)
  await panel.screenshot({ path: join(output, 'reading-directory.png'), scale: 'css' })
  await panel.getByRole('button', { name: '收起目录', exact: true }).click()
  await panel.waitForTimeout(250)
  await panel.screenshot({ path: join(output, 'reading-list.png'), scale: 'css' })
  pass('top-to-bottom directory, nested folders and selected-folder PDF drop work')
  await rail.getByRole('button', { name: '论文投稿', exact: true }).click()
  await panel.getByRole('button', { name: upcoming.title, exact: true }).waitFor()
  assert.ok(await panel.locator('.submission-title').first().evaluate(element => parseFloat(getComputedStyle(element).fontSize) >= 18))
  await panel.waitForTimeout(400)
  await panel.screenshot({ path: join(output, 'submissions.png'), scale: 'css' })
  await panel.getByRole('button', { name: upcoming.title, exact: true }).click()
  assert.equal(await panel.locator('.submission-timeline li').count(), 3)
  await panel.waitForTimeout(250)
  await panel.screenshot({ path: join(output, 'submission-timeline.png'), scale: 'css' })
  await panel.getByRole('button', { name: '标记返修完成', exact: true }).click()
  await panel.getByRole('button', { name: '重新打开返修', exact: true }).waitFor()
  const updated = unwrap(await panel.evaluate(() => window.workbench.submissionsSnapshot())).submissions.find(s => s.id === upcoming.id)
  assert.equal(updated.revisionCompleted, true); assert.deepEqual(updated.stages, upcoming.stages)
  await panel.getByRole('button', { name: '重新打开返修', exact: true }).click()
  await panel.getByRole('button', { name: '标记返修完成', exact: true }).waitFor()
  await panel.getByRole('tab', { name: '待返修', exact: true }).click()
  assert.equal(await panel.locator('.submission-entry').count(), 1)
  const edit = panel.getByRole('button', { name: `编辑投稿：${upcoming.title}`, exact: true })
  await edit.click()
  const editor = panel.getByRole('dialog', { name: '编辑投稿' })
  await editor.getByLabel('阶段 2 状态名称', { exact: true }).fill('编辑送审')
  await editor.getByLabel('阶段 2 日期', { exact: true }).fill('2026-09-14')
  await editor.getByRole('button', { name: '保存投稿', exact: true }).click()
  await editor.getByRole('alert').filter({ hasText: '状态日期需按先后顺序填写' }).waitFor()
  await editor.getByLabel('阶段 2 日期', { exact: true }).fill('2026-10-14')
  await editor.getByRole('button', { name: '添加阶段', exact: true }).click()
  await editor.getByLabel('阶段 4 状态名称', { exact: true }).fill('修回已提交')
  await editor.getByLabel('阶段 4 日期', { exact: true }).fill('2026-11-08')
  await editor.getByLabel('返修截止日期', { exact: true }).fill('2026-11-19')
  await editor.getByLabel('本轮返修已完成', { exact: true }).check()
  await editor.getByLabel('投稿已结束', { exact: true }).check()
  await panel.screenshot({ path: join(output, 'submission-editor.png'), scale: 'css' })
  await editor.getByRole('button', { name: '保存投稿', exact: true }).click()
  await editor.waitFor({ state: 'hidden' })
  assert.equal(await panel.getByRole('tab', { name: '已结束', exact: true }).getAttribute('aria-selected'), 'true')
  await panel.getByText('投稿已保存', { exact: true }).waitFor()
  const edited = unwrap(await main.evaluate(() => window.workbench.submissionsSnapshot())).submissions.find(s => s.id === upcoming.id)
  assert.equal(edited.currentStage, '修回已提交')
  assert.equal(edited.revisionDueDate, '2026-11-19')
  assert.equal(edited.revisionCompleted, true)
  assert.equal(edited.ended, true)
  assert.equal(edited.notes, upcoming.notes)
  assert.deepEqual(edited.stages.slice(0, 3).map(stage => stage.id), upcoming.stages.map(stage => stage.id))
  assert.equal(edited.stages[1].occurredOn, '2026-10-14')
  assert.equal(edited.stages[1].name, '编辑送审')
  await edit.click()
  await editor.getByLabel('投稿已结束', { exact: true }).uncheck()
  await editor.getByRole('button', { name: '保存投稿', exact: true }).click()
  await editor.waitFor({ state: 'hidden' })
  assert.equal(await panel.getByRole('tab', { name: '进行中', exact: true }).getAttribute('aria-selected'), 'true')
  pass('desktop submission editor saves dates, stages and lifecycle changes to the shared record')
  for (const scale of [.6, 1]) {
    unwrap(await panel.evaluate(scale => window.workbench.updateWidgetPreferences({ scale }), scale))
    await panel.waitForTimeout(200)
    assert.equal(await panel.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  }
  pass('submission deadlines, expandable history and revision completion preserve stage records')
  assert.deepEqual(errors, [])
} catch (error) { console.error(error); throw error } finally {
  writeFileSync(join(output, 'report.json'), JSON.stringify({ checks, errors }, null, 2))
  await app.close()
}
